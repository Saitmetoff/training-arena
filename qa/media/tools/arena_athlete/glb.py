# Reader (QA round-trip only)
# --------------------------------------------------------------------------

COMPONENT_INFO = {
    COMPONENT_FLOAT: (np.float32, 4),
    COMPONENT_UBYTE: (np.uint8, 1),
    COMPONENT_USHORT: (np.uint16, 2),
    COMPONENT_UINT: (np.uint32, 4),
}

TYPE_COUNT = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}


@dataclass
class GlbData:
    document: dict
    binary: bytes
    buffers: dict[int, np.ndarray] = field(default_factory=dict)

    def accessor(self, index: int) -> np.ndarray:
        accessor = self.document["accessors"][index]
        view = self.document["bufferViews"][accessor["bufferView"]]
        dtype, size = COMPONENT_INFO[accessor["componentType"]]
        count = TYPE_COUNT[accessor["type"]]
        start = view.get("byteOffset", 0) + accessor.get("byteOffset", 0)
        items = count * accessor["count"]
        array = np.frombuffer(self.binary, dtype=dtype, count=items, offset=start)
        array = array.reshape(accessor["count"], count)
        if accessor.get("normalized"):
            array = array.astype(np.float64)
            if dtype == np.uint8:
                array = array / 255.0
            elif dtype == np.uint16:
                array = array / 65535.0
        return array

    def quaternion_matrix(self, quaternion: np.ndarray) -> np.ndarray:
        x, y, z, w = (float(value) for value in quaternion)
        return np.array(
            [
                [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
            ]
        )

    def sample_track(self, track_index: int, time: float) -> dict[int, dict[str, np.ndarray]]:
        """Return node -> {"rotation": 3x3, "translation": vec3} for animated paths only."""
        animation = self.document["animations"][track_index]
        results: dict[int, dict[str, np.ndarray]] = {}
        for channel in animation["channels"]:
            sampler = animation["samplers"][channel["sampler"]]
            times = self.accessor(sampler["input"]).reshape(-1)
            values = self.accessor(sampler["output"])
            node = channel["target"]["node"]
            path = channel["target"]["path"]
            position = int(np.searchsorted(times, time, side="right") - 1)
            position = max(0, min(position, len(times) - 2))
            span = max(float(times[position + 1] - times[position]), 1e-9)
            amount = float(np.clip((time - times[position]) / span, 0.0, 1.0))
            entry = results.setdefault(node, {})
            if path == "rotation":
                a = values[position].astype(float)
                b = values[position + 1].astype(float)
                if float(np.dot(a, b)) < 0.0:
                    b = -b
                quaternion = a + (b - a) * amount
                quaternion /= np.linalg.norm(quaternion)
                entry["rotation"] = self.quaternion_matrix(quaternion)
            else:
                entry["translation"] = values[position].astype(float) + (
                    values[position + 1].astype(float) - values[position].astype(float)
                ) * amount
        return results

    def node_world_matrices(self, track_index: int, time: float) -> dict[int, np.ndarray]:
        document = self.document
        animated = self.sample_track(track_index, time)

        def world(node_index: int) -> np.ndarray:
            node = document["nodes"][node_index]
            entry = animated.get(node_index, {})
            translation = entry.get("translation")
            if translation is None:
                translation = np.array(node.get("translation", [0.0, 0.0, 0.0]), dtype=float)
            rotation = entry.get("rotation")
            if rotation is None:
                quaternion = np.array(node.get("rotation", [0.0, 0.0, 0.0, 1.0]), dtype=float)
                rotation = self.quaternion_matrix(quaternion)
            matrix = np.eye(4)
            matrix[:3, :3] = rotation
            matrix[:3, 3] = translation
            parent = node.get("_parent")
            if parent is None:
                return matrix
            return world(parent) @ matrix

        for node in document["nodes"]:
            node["_parent"] = None
        for index, node in enumerate(document["nodes"]):
            for child in node.get("children", []):
                document["nodes"][child]["_parent"] = index
        return {index: world(index) for index in range(len(document["nodes"]))}

    def skin_vertices(self, track_index: int, time: float, primitive_index: int = 0) -> np.ndarray:
        document = self.document
        skin = document["skins"][0]
        joint_nodes = skin["joints"]
        inverse_bind = self.accessor(skin["inverseBindMatrices"]).astype(float).reshape(-1, 4, 4)
        inverse_bind = np.transpose(inverse_bind, (0, 2, 1))  # back to row-major
        world = self.node_world_matrices(track_index, time)

        primitive = document["meshes"][0]["primitives"][primitive_index]
        indices = self.accessor(primitive["indices"]).reshape(-1).astype(int)
        positions = self.accessor(primitive["attributes"]["POSITION"]).astype(float)
        joints = self.accessor(primitive["attributes"]["JOINTS_0"]).astype(int)
        weights = self.accessor(primitive["attributes"]["WEIGHTS_0"]).astype(float)

        output = np.zeros_like(positions)
        for joint_slot in range(joints.shape[1]):
            joint_ids = joints[:, joint_slot]
            weight = weights[:, joint_slot]
            for joint_index in np.unique(joint_ids):
                selection = joint_ids == joint_index
                matrix = world[joint_nodes[joint_index]] @ inverse_bind[joint_index]
                transformed = positions[selection] @ matrix[:3, :3].T + matrix[:3, 3]
                output[selection] += transformed * weight[selection][:, None]
        return output[indices]


def read_glb(path: Path) -> GlbData:
    with path.open("rb") as handle:
        data = handle.read()
    magic, version, _ = struct.unpack_from("<III", data, 0)
    if magic != GLB_MAGIC or version != 2:
        raise ValueError("not a glTF 2.0 binary")
    offset = 12
    document: dict | None = None
    binary = b""
    while offset < len(data):
        length, chunk_type = struct.unpack_from("<II", data, offset)
        payload = data[offset + 8 : offset + 8 + length]
        if chunk_type == CHUNK_JSON:
            document = json.loads(payload.decode("utf-8"))
        elif chunk_type == CHUNK_BIN:
            binary = payload
        offset += 8 + length
    if document is None:
        raise ValueError("missing JSON chunk")
    return GlbData(document=document, binary=binary)
