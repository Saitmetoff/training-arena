"""Minimal glTF 2.0 binary exporter plus a reader used by the round-trip QA.

Written by hand so the media package has no third-party 3D dependency and the
generated bytes are deterministic. Only what the athlete needs is supported:
one skinned mesh, per-material primitives, a joint hierarchy, rotation tracks
and a root translation track.
"""

from __future__ import annotations

import json
import math
import struct
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from .mesh import AthleteMesh, MATERIAL_COLORS, MATERIALS
from .rig import Pose
from .spec import ATHLETE_ID, ATHLETE_NAME, PACKAGE_VERSION, PALETTE
from .spec import BONE_HEAD, BONE_NAMES, BONE_PARENT, SKELETON

GLB_MAGIC = 0x46546C67
CHUNK_JSON = 0x4E4F534A
CHUNK_BIN = 0x004E4942

COMPONENT_FLOAT = 5126
COMPONENT_UBYTE = 5121
COMPONENT_USHORT = 5123
COMPONENT_UINT = 5125

TARGET_ARRAY = 34962
TARGET_ELEMENT = 34963


def _align(data: bytes, alignment: int = 4) -> bytes:
    remainder = len(data) % alignment
    if remainder == 0:
        return data
    return data + b"\x00" * (alignment - remainder)


def mat_to_quat(matrix: np.ndarray) -> tuple[float, float, float, float]:
    trace = float(matrix[0, 0] + matrix[1, 1] + matrix[2, 2])
    if trace > 0.0:
        scale = math.sqrt(trace + 1.0) * 2.0
        w = 0.25 * scale
        x = (matrix[2, 1] - matrix[1, 2]) / scale
        y = (matrix[0, 2] - matrix[2, 0]) / scale
        z = (matrix[1, 0] - matrix[0, 1]) / scale
    elif matrix[0, 0] > matrix[1, 1] and matrix[0, 0] > matrix[2, 2]:
        scale = math.sqrt(1.0 + matrix[0, 0] - matrix[1, 1] - matrix[2, 2]) * 2.0
        w = (matrix[2, 1] - matrix[1, 2]) / scale
        x = 0.25 * scale
        y = (matrix[0, 1] + matrix[1, 0]) / scale
        z = (matrix[0, 2] + matrix[2, 0]) / scale
    elif matrix[1, 1] > matrix[2, 2]:
        scale = math.sqrt(1.0 + matrix[1, 1] - matrix[0, 0] - matrix[2, 2]) * 2.0
        w = (matrix[0, 2] - matrix[2, 0]) / scale
        x = (matrix[0, 1] + matrix[1, 0]) / scale
        y = 0.25 * scale
        z = (matrix[1, 2] + matrix[2, 1]) / scale
    else:
        scale = math.sqrt(1.0 + matrix[2, 2] - matrix[0, 0] - matrix[1, 1]) * 2.0
        w = (matrix[1, 0] - matrix[0, 1]) / scale
        x = (matrix[0, 2] + matrix[2, 0]) / scale
        y = (matrix[1, 2] + matrix[2, 1]) / scale
        z = 0.25 * scale
    quaternion = np.array([x, y, z, w])
    return tuple(float(value) for value in quaternion)


def quat_continuity(quaternions: np.ndarray) -> np.ndarray:
    """Remove sign flips so LINEAR interpolation between samples is short-path."""
    output = np.array(quaternions, dtype=float)
    for index in range(1, len(output)):
        if float(np.dot(output[index - 1], output[index])) < 0.0:
            output[index] = -output[index]
    return output


@dataclass
class AnimationTrack:
    name: str
    times: np.ndarray  # (F,) seconds
    rotations: dict[str, np.ndarray] = field(default_factory=dict)  # (F, 4) xyzw per bone
    translations: dict[str, np.ndarray] = field(default_factory=dict)  # (F, 3) per bone


def pose_to_local(pose: Pose) -> dict[str, tuple[np.ndarray, np.ndarray]]:
    """World pose -> (local rotation, local translation) per bone."""
    local: dict[str, tuple[np.ndarray, np.ndarray]] = {}
    for name in BONE_NAMES:
        parent = BONE_PARENT[name]
        if parent is None:
            local[name] = (pose.rotations[name], pose.heads[name])
        else:
            local_rotation = pose.rotations[parent].T @ pose.rotations[name]
            local_translation = pose.rotations[parent].T @ (pose.heads[name] - pose.heads[parent])
            local[name] = (local_rotation, local_translation)
    return local


def build_track(name: str, frames: list[Pose], fps: float) -> AnimationTrack:
    times = np.array([index / fps for index in range(len(frames))], dtype=float)
    rotations: dict[str, np.ndarray] = {}
    translations: dict[str, np.ndarray] = {}
    for bone in BONE_NAMES:
        local = [pose_to_local(frame)[bone] for frame in frames]
        rotations[bone] = quat_continuity(np.array([mat_to_quat(rotation) for rotation, _ in local]))
        if bone == "hips":
            translations[bone] = np.array([translation for _, translation in local], dtype=float)
    return AnimationTrack(name=name, times=times, rotations=rotations, translations=translations)


class GlbBuilder:
    def __init__(self) -> None:
        self.bin_parts: list[bytes] = []
        self.buffer_views: list[dict] = []
        self.accessors: list[dict] = []
        self.offset = 0

    def _add_view(self, data: bytes, target: int | None = None) -> int:
        padded = _align(data, 4)
        view = {
            "buffer": 0,
            "byteOffset": self.offset,
            "byteLength": len(data),
        }
        if target is not None:
            view["target"] = target
        self.buffer_views.append(view)
        self.bin_parts.append(padded)
        self.offset += len(padded)
        return len(self.buffer_views) - 1

    def add_accessor(
        self,
        array: np.ndarray,
        component_type: int,
        type_name: str,
        target: int | None = None,
        min_max: bool = False,
        normalized: bool = False,
    ) -> tuple[int, int]:
        data = array.tobytes(order="C")
        view = self._add_view(data, target)
        accessor = {
            "bufferView": view,
            "componentType": component_type,
            "count": int(array.shape[0]),
            "type": type_name,
        }
        if normalized:
            accessor["normalized"] = True
        if min_max:
            if type_name == "SCALAR":
                accessor["min"] = [float(array.min())]
                accessor["max"] = [float(array.max())]
            else:
                accessor["min"] = [float(value) for value in array.min(axis=0)]
                accessor["max"] = [float(value) for value in array.max(axis=0)]
        self.accessors.append(accessor)
        return len(self.accessors) - 1

    def finish(self) -> bytes:
        return b"".join(self.bin_parts)


def export_glb(
    mesh: AthleteMesh,
    tracks: list[AnimationTrack],
    output_path: Path,
    *,
    generated_at: str,
) -> None:
    builder = GlbBuilder()

    positions = builder.add_accessor(mesh.vertices.astype(np.float32), COMPONENT_FLOAT, "VEC3", TARGET_ARRAY, min_max=True)
    normals = builder.add_accessor(mesh.normals.astype(np.float32), COMPONENT_FLOAT, "VEC3", TARGET_ARRAY)

    joints = np.zeros((len(mesh.vertices), 4), dtype=np.uint8)
    joints[:, 0] = mesh.joints.astype(np.uint8)
    joints_accessor = builder.add_accessor(joints, COMPONENT_UBYTE, "VEC4", TARGET_ARRAY)

    weights = np.zeros((len(mesh.vertices), 4), dtype=np.uint8)
    weights[:, 0] = 255
    weights_accessor = builder.add_accessor(weights, COMPONENT_UBYTE, "VEC4", TARGET_ARRAY, normalized=True)

    primitives = []
    for material_index in range(len(MATERIALS)):
        faces = mesh.triangles[mesh.triangle_materials == material_index]
        if len(faces) == 0:
            continue
        flat = faces.astype(np.uint32).reshape(-1)
        component = COMPONENT_USHORT if len(mesh.vertices) < 65536 else COMPONENT_UINT
        dtype = np.uint16 if component == COMPONENT_USHORT else np.uint32
        indices = builder.add_accessor(flat.astype(dtype), component, "SCALAR", TARGET_ELEMENT)
        primitives.append(
            {
                "attributes": {
                    "POSITION": positions,
                    "NORMAL": normals,
                    "JOINTS_0": joints_accessor,
                    "WEIGHTS_0": weights_accessor,
                },
                "indices": indices,
                "material": material_index,
                "mode": 4,
            }
        )

    joint_indices = list(range(1, len(BONE_NAMES) + 1))  # node 0 is the mesh node
    inverse_bind = []
    for name in BONE_NAMES:
        matrix = np.eye(4)
        matrix[:3, 3] = -np.array(BONE_HEAD[name])
        inverse_bind.append(matrix.T.reshape(-1))  # column-major
    inverse_bind_accessor = builder.add_accessor(np.array(inverse_bind, dtype=np.float32), COMPONENT_FLOAT, "MAT4")

    animations = []
    for track in tracks:
        samplers = []
        channels = []
        time_accessor = builder.add_accessor(track.times.astype(np.float32), COMPONENT_FLOAT, "SCALAR", min_max=True)
        for bone in BONE_NAMES:
            output = builder.add_accessor(track.rotations[bone].astype(np.float32), COMPONENT_FLOAT, "VEC4")
            samplers.append({"input": time_accessor, "output": output, "interpolation": "LINEAR"})
            channels.append(
                {
                    "sampler": len(samplers) - 1,
                    "target": {"node": joint_indices[BONE_NAMES.index(bone)], "path": "rotation"},
                }
            )
            if bone in track.translations:
                output_t = builder.add_accessor(track.translations[bone].astype(np.float32), COMPONENT_FLOAT, "VEC3")
                samplers.append({"input": time_accessor, "output": output_t, "interpolation": "LINEAR"})
                channels.append(
                    {
                        "sampler": len(samplers) - 1,
                        "target": {"node": joint_indices[BONE_NAMES.index(bone)], "path": "translation"},
                    }
                )
        animations.append({"name": track.name, "samplers": samplers, "channels": channels})

    nodes: list[dict] = [
        {"name": "AthleteMesh", "mesh": 0, "skin": 0},
    ]
    for index, name in enumerate(BONE_NAMES):
        node: dict = {"name": name}
        parent = BONE_PARENT[name]
        if parent is None:
            node["translation"] = [float(value) for value in BONE_HEAD[name]]
        else:
            offset = np.array(BONE_HEAD[name]) - np.array(BONE_HEAD[parent])
            node["translation"] = [float(value) for value in offset]
        node["rotation"] = [0.0, 0.0, 0.0, 1.0]
        children = [1 + BONE_NAMES.index(other) for other in BONE_NAMES if BONE_PARENT[other] == name]
        if children:
            node["children"] = children
        nodes.append(node)

    materials = []
    for name in MATERIALS:
        color = MATERIAL_COLORS[name]
        materials.append(
            {
                "name": name,
                "pbrMetallicRoughness": {
                    "baseColorFactor": [float(value) for value in color] + [1.0],
                    "metallicFactor": 0.0,
                    "roughnessFactor": 0.55 if name == "accent" else 0.82,
                },
                "doubleSided": False,
            }
        )

    document = {
        "asset": {
            "version": "2.0",
            "generator": f"arena_athlete GLB exporter {PACKAGE_VERSION}",
            "copyright": "Training Arena project",
            "extras": {
                "athlete_id": ATHLETE_ID,
                "athlete_name": ATHLETE_NAME,
                "generated_at": generated_at,
                "source": "procedural generation, see docs/media/PROVENANCE.md",
            },
        },
        "scene": 0,
        "scenes": [{"name": "ArenaAthlete", "nodes": [0, 1]}],
        "nodes": nodes,
        "skins": [
            {
                "name": "ArenaRig",
                "skeleton": 1,
                "joints": joint_indices,
                "inverseBindMatrices": inverse_bind_accessor,
            }
        ],
        "meshes": [{"name": "AthleteMesh", "primitives": primitives}],
        "materials": materials,
        "animations": animations,
        "accessors": builder.accessors,
        "bufferViews": builder.buffer_views,
        "buffers": [{"byteLength": 0}],
    }

    binary = builder.finish()
    document["buffers"][0]["byteLength"] = len(binary)
    json_bytes = json.dumps(document, separators=(",", ":")).encode("utf-8")
    json_bytes += b" " * ((4 - len(json_bytes) % 4) % 4)

    total = 12 + 8 + len(json_bytes) + 8 + len(binary)
    with output_path.open("wb") as handle:
        handle.write(struct.pack("<III", GLB_MAGIC, 2, total))
        handle.write(struct.pack("<II", len(json_bytes), CHUNK_JSON))
        handle.write(json_bytes)
        handle.write(struct.pack("<II", len(binary), CHUNK_BIN))
        handle.write(binary)


